
public class Forquilla {
    int numero;
    boolean enUs;


    public Forquilla(int numero) {
        this.numero = numero;
    }

    public int getNumero() {
        return numero;
    }

    public void setNumero(int numero) {
        this.numero = numero;
    }

    public void setEnUs(boolean enUs) {
        this.enUs = enUs;
    }

    public boolean  isEnUs() {
        return enUs;
    }

}
